#!/usr/bin/env python3
# 生成 GBK(CP936) → Unicode 映射表（Go 源码）。
# 索引 = (首字节 - 0x81) * 191 + (尾字节 - 0x40)，未映射槽位为 U+FFFD。
# 用法：python3 tools/gen_gbk_table.py > src/gbk_table.go
import sys

LEADS = range(0x81, 0xFF)
TRAILS = range(0x40, 0xFF)


def build():
    out = []
    for hi in LEADS:
        for lo in TRAILS:
            try:
                ch = bytes((hi, lo)).decode("gbk")
            except UnicodeDecodeError:
                ch = "\ufffd"
            if len(ch) != 1:
                ch = "\ufffd"
            out.append(ch)
    return out


def go_literal(chars):
    buf = []
    for ch in chars:
        o = ord(ch)
        if ch == '"':
            buf.append('\\"')
        elif ch == "\\":
            buf.append("\\\\")
        elif 0x20 <= o < 0x7F:
            buf.append(ch)
        elif o <= 0xFFFF:
            buf.append("\\u%04x" % o)
        else:
            buf.append("\\U%08x" % o)
    return "".join(buf)


def main():
    chars = build()
    assert len(chars) == len(LEADS) * len(TRAILS)
    body = go_literal(chars)
    w = sys.stdout.write
    w("// Code generated by tools/gen_gbk_table.py; DO NOT EDIT.\n\n")
    w("package main\n\n")
    w("// gbkTable 把 GBK(CP936) 双字节逐字映射成 Unicode。\n")
    w("// \u7d22\u5f15 = (lead-0x81)*191 + (trail-0x40)，未映射的槽位是 U+FFFD。\n")
    w("const gbkTable = \"" + body + "\"\n\n")
    w("var gbkRunes []rune\n\n")
    w("// gbkLookup 查一个双字节 GBK 字符；返回 false 表示这个组合没有定义。\n")
    w("func gbkLookup(lead, trail byte) (rune, bool) {\n")
    w("\tif lead < 0x81 || lead > 0xFE || trail < 0x40 || trail > 0xFE {\n")
    w("\t\treturn 0, false\n")
    w("\t}\n")
    w("\tif gbkRunes == nil {\n")
    w("\t\tgbkRunes = []rune(gbkTable)\n")
    w("\t}\n")
    w("\tr := gbkRunes[int(lead-0x81)*191+int(trail-0x40)]\n")
    w("\tif r == '\\uFFFD' {\n")
    w("\t\treturn 0, false\n")
    w("\t}\n")
    w("\treturn r, true\n")
    w("}\n")


if __name__ == "__main__":
    main()
